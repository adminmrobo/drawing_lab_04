"""본문 '숫자로 한 번 해 보기'·대화·퀴즈 숫자와 평가 점수 검산. python3 build/check_numbers.py"""
import math, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from content_a import P1, P2, P3
from content_b import P4, P5, P6
ok = True
def chk(name, got, want, tol=0.01):
    global ok
    good = abs(got - want) <= tol
    ok &= good
    print(("OK " if good else "XX "), name, round(got, 4), "기대", want)
D = lambda x: math.degrees(math.atan(x)); cos = lambda d: math.cos(math.radians(d)); sin = lambda d: math.sin(math.radians(d))
# 1부
chk("1-1 기울기 0.5", 0.5 / 10, 0.05); chk("1-1 각도 0.5", D(0.05), 2.9, 0.05); chk("1-1 각도 1.5", D(0.15), 8.5, 0.05); chk("1-1 각도 −0.8", D(-0.08), -4.6, 0.05)
chk("1-3 고개15 안쪽", cos(40), 0.766, 0.001); chk("1-3 고개15 앞쪽", cos(10), 0.985, 0.001); chk("1-3 고개15 비율", cos(40) / cos(10), 0.78, 0.005)
chk("1-3 고개30 안쪽", cos(55), 0.574, 0.001); chk("1-3 고개30 앞쪽", cos(5), 0.996, 0.001); chk("1-3 고개30 비율", cos(55) / cos(5), 0.58, 0.005)
chk("1-3 고개45 안쪽", cos(70), 0.342, 0.001); chk("1-3 고개45 앞쪽", cos(20), 0.940, 0.001); chk("1-3 고개45 비율", cos(70) / cos(20), 0.36, 0.005)
chk("1-4 홍채/속눈썹 10/20", 10 / 20, 0.5)
# 2부
chk("2-2 곱하기", 200 * 150 / 255, 117.6, 0.05); chk("2-2 더하기 60%", 120 + 150 * 0.6, 210); chk("2-2 더하기 100%", 120 + 200, 320)
chk("2-2 대화 곱하기", 170 * 150 / 255, 100); chk("2-2 대화 더하기", 170 + 230 * 0.6, 308)
chk("2-1 피부 밝기", (247 + 224 + 206) / 3, 225.7, 0.05); chk("2-1 흰자 예 밝기", (238 + 230 + 226) / 3, 231.3, 0.05)
# 3부
chk("3-2 귀 정면", 10 * sin(0) + 1.5, 1.5); chk("3-2 귀 45", 10 * sin(45) + 1.5, 8.6, 0.05); chk("3-2 귀 옆", 10 * sin(90) + 1.5, 11.5); chk("3-2 귀 가운데 높이", (50 + 72) / 2, 61)
chk("3-3 10도", 10 * sin(10), 1.7, 0.05); chk("3-3 20도", 10 * sin(20), 3.4, 0.05); chk("3-3 30도", 10 * sin(30), 5); chk("3-3 패널 20도(깊이 60)", 60 * sin(20), 20.5, 0.05)
# 4부
chk("4-1 넓이 1.1", 1.1 ** 2, 1.21); chk("4-1 넓이 1.15", 1.15 ** 2, 1.32, 0.005); chk("4-1 얼굴 몫", 1 / 1.21, 0.83, 0.005)
# 5부
chk("5-3 전체", 1024 * 1536, 1572864); chk("5-3 눈 가림", 360 * 120, 43200); chk("5-3 눈 몫", 43200 / 1572864, 0.027, 0.0005)
chk("5-3 여유 20%", 432 * 144, 62208); chk("5-3 여유 몫", 62208 / 1572864, 0.040, 0.0005); chk("5-3 입 몫(여유 20%)", 240 * 132 / 1572864, 0.020, 0.0005)
chk("5-3 얼굴 전체 몫", 620 * 700 / 1572864, 0.28, 0.005)
for P in (P1, P2, P3, P4, P5, P6):
    J = P["judge"]; sa, sb = sum(J["a"][1]), sum(J["b"][1]); txt = J["result"][0][2]
    good = f"{sb} : 주판봇 {sa}" in txt; ok &= good
    print(("OK " if good else "XX "), P["no"], "부 평가", sb, ":", sa, txt[:22])
print("전체 통과" if ok else "검산 실패"); sys.exit(0 if ok else 1)
